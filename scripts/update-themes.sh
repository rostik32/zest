#!/bin/bash
# Downloads popular VS Code color themes from Open VSX (open-vsx.org) and converts them
# into zest themes in themes/. Each theme's license text goes to themes/LICENSES, and
# themes/SOURCES.md lists where every theme comes from.
#
# Only add extensions whose license allows redistribution (MIT, ISC, BSD, Apache-2.0).
# The second column is the license as checked by hand: Open VSX doesn't always say.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"

# namespace/name         license   name suffix (optional)
extensions=(
  "vscode/theme-defaults           MIT  (VS Code)"
  "vscode/theme-monokai            MIT"
  "vscode/theme-monokai-dimmed     MIT"
  "vscode/theme-solarized-dark     MIT"
  "vscode/theme-solarized-light    MIT"
  "vscode/theme-abyss              MIT"
  "vscode/theme-kimbie-dark        MIT"
  "vscode/theme-quietlight         MIT"
  "vscode/theme-tomorrow-night-blue MIT"
  "zhuangtongfa/material-theme     MIT"
  "dracula-theme/theme-dracula     MIT"
  "Catppuccin/catppuccin-vsc       MIT"
  "enkia/tokyo-night               MIT"
  "GitHub/github-vscode-theme      MIT"
  "sdras/night-owl                 MIT"
  "teabyii/ayu                     MIT"
  "arcticicestudio/nord-visual-studio-code MIT"
  "mvllow/rose-pine                MIT"
  "jdinhlife/gruvbox               MIT"
  "antfu/theme-vitesse             MIT"
  "wesbos/theme-cobalt2            MIT"
  "RobbOwen/synthwave-vscode       MIT"
  "akamud/vscode-theme-onelight    MIT"
  "jolaleye/horizon-theme-vscode   MIT"
  "sainnhe/everforest              MIT"
  "liviuschera/noctis              MIT"
  "atomiks/moonlight               MIT"
)

swift build -c release --product zest >/dev/null
zest="$(swift build -c release --show-bin-path)/zest"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

rm -rf themes
mkdir -p themes/LICENSES


for entry in "${extensions[@]}"; do
  read -r id license suffix <<< "$entry"
  meta=$(curl -fsSL "https://open-vsx.org/api/$id/latest")
  url=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["files"]["download"])' <<< "$meta")
  display=$(python3 -c 'import json,sys; d=json.load(sys.stdin); print(d.get("displayName") or d["name"])' <<< "$meta")
  version=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["version"])' <<< "$meta")
  slug=${id//\//.}
  dir="$work/$slug"
  mkdir -p "$dir"
  curl -fsSL "$url" -o "$dir/ext.vsix"
  unzip -q -o "$dir/ext.vsix" -d "$dir"
  author=$(python3 - "$dir/extension/package.json" "$id" <<'PY'
import json, sys
p = json.load(open(sys.argv[1]))
a = p.get("author")
name = a.get("name") if isinstance(a, dict) else a
if p.get("publisher") == "vscode" or sys.argv[2].startswith("vscode/"):
    name = "Microsoft"
import re
name = re.sub(r"\s*[<(][^>)]*[>)]", "", name or "").strip()  # drop e-mail addresses and URLs
print(name or p.get("publisher") or sys.argv[2].split("/")[0])
PY
)
  args=(theme import "$dir/extension" --out themes --source "$display by $author ($license)")
  [ -n "${suffix:-}" ] && args+=(--suffix " $suffix")
  "$zest" "${args[@]}" | sed 's/.* -> //' | while read -r file; do
    echo "$file|$id|$display|$author|$version|$license" >> "$work/imported.txt"
  done
  license_file=$(find "$dir/extension" -maxdepth 1 -iname 'license*' | head -1)
  if [ -n "$license_file" ]; then
    cp "$license_file" "themes/LICENSES/$slug.txt"
  else
    echo "warning: $id has no license file" >&2
  fi
  echo "$id"
done
# Variants that differ only in font style (Italic, Bold, No Italics) have the same
# colors: keep the one with the shortest name.
python3 - <<'PY'
import pathlib, re
groups = {}
for f in sorted(pathlib.Path("themes").glob("*.yaml")):
    text = f.read_text()
    colors = text[text.index("colors:"):]
    name = re.search(r'^name: "(.*)"$', text, re.M).group(1)
    groups.setdefault(colors, []).append((len(name), name, f))
for items in groups.values():
    items.sort()
    for _, name, f in items[1:]:
        print(f"same colors as {items[0][1]}: dropping {name}")
        f.unlink()
PY
{
  echo "# Theme sources"
  echo
  echo "Generated by \`scripts/update-themes.sh\`. The colors of each theme come from the VS Code"
  echo "extension below, under its license; the full license texts are in [LICENSES](LICENSES)."
  echo
  echo "| Extension | Author | Version | License | Themes |"
  echo "| --- | --- | --- | --- | --- |"
} > themes/SOURCES.md
# One row per extension, listing the themes that are left.
python3 - "$work/imported.txt" >> themes/SOURCES.md <<'PY'
import os, re, sys
rows = {}
for line in open(sys.argv[1]):
    file, ext, display, author, version, license = line.rstrip("\n").split("|")
    if not os.path.exists(file):
        continue
    name = re.search(r'^name: "(.*)"$', open(file).read(), re.M).group(1)
    rows.setdefault((ext, display, author, version, license), []).append(name)
for (ext, display, author, version, license), names in rows.items():
    print(f"| [{display}](https://open-vsx.org/extension/{ext}) | {author} | {version} | {license} | {', '.join(names)} |")
PY
echo "$(ls themes/*.yaml | wc -l | tr -d ' ') themes in themes/"
